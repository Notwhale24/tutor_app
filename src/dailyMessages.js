export const DAILY_MESSAGE_COUNT = bannerSubjects.length * bannerActions.length;
const EPOCH = Date.UTC(2026, 9, 22) / 86400000;
export function localDayNumber(date = new Date()) {
  return Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000;
}
function phrase(left, right, day, seed, join = ' ') {
  const count = left.length * right.length;
  const index = ((day * 613 + seed) % count + count) % count;
  return `${left[Math.floor(index / right.length)]}${join}${right[index % right.length]}`;
}
export function getDailyMessages(date = new Date()) {
  const day = localDayNumber(date) - EPOCH;
  return {
    bannerTitle: phrase(bannerSubjects, bannerActions, day, 119),
    bannerSubtitle: phrase(bannerIntroductions, bannerEndings, day, 487),
    noteLabel: phrase(noteIntroductions, noteDirections, day, 731, ' — '),
    noteTitle: phrase(noteSubjects, noteActions, day, 277),
  };
}
